async function startTestServer(){
  serverProcess=spawn(process.execPath,['server.mjs'],{cwd:__dirname,env:{...process.env,DORM_PORT:String(testPort),DORM_DB_PATH:testDatabase},stdio:['ignore','pipe','pipe'],windowsHide:true});
  await new Promise((resolve,reject)=>{
    const timeout=setTimeout(()=>reject(new Error('Test server did not start')),10000);
    let output='';serverProcess.stdout.on('data',chunk=>{output+=chunk;if(output.includes('Local:')){clearTimeout(timeout);resolve();}});
    serverProcess.once('exit',code=>{clearTimeout(timeout);reject(new Error(`Test server exited: ${code}`));});
    serverProcess.stderr.on('data',chunk=>{if(!String(chunk).includes('ExperimentalWarning')&&!String(chunk).includes('trace-warnings'))process.stderr.write(chunk);});
  });
}
